export { en, zh };

let current: Record<Key, string> = en;

/** 按 Obsidian 的语言代码切换：zh 开头用简体中文，其余一律英文 */
export function setLocale(lang: string): void {
  current = lang.toLowerCase().startsWith("zh") ? zh : en;
}

/** 当前生效的语言，"zh" 或 "en" */
export function getLocale(): "zh" | "en" {
  return current === zh ? "zh" : "en";
}

/** 取文案；vars 按 `{name}` 插值，找不到的占位符原样保留 */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const text = current[key] ?? en[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
