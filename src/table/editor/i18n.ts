let lang: "zh" | "en" = "en";

export function setLanguage(code: string | null | undefined): void {
  lang = code?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function t(key: Key): string {
  return (lang === "zh" ? zh : en)[key];
}
